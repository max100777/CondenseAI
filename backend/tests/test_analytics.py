def test_analytics_api_summary_and_reset(client):
    """Test GET /api/analytics/summary and POST /api/analytics/reset."""
    # First calculate to populate session state
    payload = {
        "time_points_s": [1.0, 2.0],
        "freshwater_mass_kg": [0.001, 0.002],
        "freshwater_rates_l_h": [3.6, 3.6],
        "fluxes_lmh": [2.5, 2.5],
        "agmd_powers_w": [80.0, 80.0],
    }
    client.post("/api/analytics/calculate", json=payload)

    # Now get summary
    res_get = client.get("/api/analytics/summary")
    assert res_get.status_code == 200
    data_get = res_get.json()
    assert data_get["total_freshwater_volume_l"] == 0.002

    # Now reset
    res_reset = client.post("/api/analytics/reset")
    assert res_reset.status_code == 200
    assert res_reset.json()["status"] == "reset"

    # Getting summary after reset should return 404 (no active analytics session)
    res_after = client.get("/api/analytics/summary")
    assert res_after.status_code == 404
