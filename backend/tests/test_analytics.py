def test_compute_from_time_series():
    """Verify complete time-series aggregation into AnalyticsSummary and Points."""
    time_points = [1.0, 2.0, 3.0]
    fw_masses = [0.001, 0.002, 0.003]
    fw_rates = [3.6, 3.6, 3.6]
    fluxes = [5.0, 5.0, 5.0]
    agmd_powers = [100.0, 100.0, 100.0]

    summary, points = AnalyticsModel.compute_from_time_series(
        time_points_s=time_points,
        freshwater_mass_kg=fw_masses,
        freshwater_rates_l_h=fw_rates,
        fluxes_lmh=fluxes,
        agmd_powers_w=agmd_powers,
        total_gpu_heat_j=1000.0,
        total_hx_heat_j=800.0,
        initial_feed_mass_kg=10.0,
        energy_balance_residual_j=1e-7,
    )

    assert summary.simulation_duration_s == 3.0
    assert summary.total_freshwater_mass_kg == 0.003
    assert pytest.approx(summary.total_freshwater_volume_l, rel=1e-5) == 0.003
    assert pytest.approx(summary.total_freshwater_volume_ml, rel=1e-5) == 3.0
    assert summary.total_agmd_energy_j == 300.0
    assert pytest.approx(summary.total_agmd_energy_kwh, rel=1e-6) == 300.0 / 3.6e6
    assert summary.average_flux_lmh == 5.0
    assert summary.maximum_flux_lmh == 5.0
    assert summary.minimum_flux_lmh == 5.0
    assert summary.heat_exchanger_recovery_percent == 80.0
    assert pytest.approx(summary.heat_utilization_percent, rel=1e-5) == (300.0 / 800.0) * 100.0
    assert pytest.approx(summary.gpu_to_agmd_efficiency_percent, rel=1e-5) == (300.0 / 1000.0) * 100.0
    assert pytest.approx(summary.water_recovery_percent, rel=1e-5) == (0.003 / 10.0) * 100.0
    assert len(points) == 3


