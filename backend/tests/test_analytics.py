def test_stec_calculation():
    """Verify Specific Thermal Energy Consumption in kWh_th/m³."""
    e_agmd_kwh = 1.0  # 1 kWh_th
    # 0.001 m³ = 1 L of water
    v_water_m3 = 0.001
    stec = AnalyticsModel.calculate_stec(e_agmd_kwh, v_water_m3)
    assert pytest.approx(stec, rel=1e-5) == 1000.0

    # Zero water volume must return None, not ZeroDivisionError
    assert AnalyticsModel.calculate_stec(e_agmd_kwh, 0.0) is None
    assert AnalyticsModel.calculate_stec(e_agmd_kwh, -0.5) is None


