def test_production_rates_calculation():
    """Verify conversion of vapor mass flux and membrane area to L/h and LMH."""
    j_mass = 1.0e-3  # 1.0 g/(m²·s) = 0.001 kg/(m²·s)
    area = 0.04 * 0.04  # 0.0016 m²
    rho_w = 1000.0

    mass_rate, vol_rate, flux_lmh = AnalyticsModel.calculate_production_rates(
        mass_flux_kg_m2_s=j_mass,
        membrane_area_m2=area,
        water_density_kg_m3=rho_w,
    )

    expected_mass_rate = j_mass * area  # 1.6e-6 kg/s
    expected_vol_rate = (expected_mass_rate / 1000.0) * 3.6e6  # 5.76e-3 L/h
    expected_flux_lmh = (j_mass / 1000.0) * 3.6e6  # 3.6 LMH

    assert pytest.approx(mass_rate, rel=1e-6) == expected_mass_rate
    assert pytest.approx(vol_rate, rel=1e-6) == expected_vol_rate
    assert pytest.approx(flux_lmh, rel=1e-6) == expected_flux_lmh


def test_time_weighted_average_flux():
    """Verify time-weighted average flux with unequal step durations."""
    fluxes = [10.0, 20.0, 30.0]
    dt_list = [1.0, 2.0, 3.0]  # Total time = 6.0 s
    # J_avg = (10*1 + 20*2 + 30*3) / 6 = (10 + 40 + 90) / 6 = 140 / 6 = 23.3333...
    avg_flux = AnalyticsModel.calculate_time_weighted_average_flux(fluxes, dt_list)
    assert pytest.approx(avg_flux, rel=1e-6) == 140.0 / 6.0

    # Empty or zero-duration list handling
    assert AnalyticsModel.calculate_time_weighted_average_flux([], []) == 0.0
    assert AnalyticsModel.calculate_time_weighted_average_flux([10.0], [0.0]) == 0.0


def test_efficiency_metrics():
    """Verify calculation of eta_HX, eta_utilization, and eta_GPU->AGMD."""
    e_gpu = 10000.0  # Joules generated by GPU
    e_hx = 8000.0    # Joules recovered by HX
    e_agmd = 4000.0  # Joules consumed by AGMD

    eta_hx, eta_util, eta_gpu_agmd = AnalyticsModel.calculate_efficiencies(e_gpu, e_hx, e_agmd)

    assert pytest.approx(eta_hx, rel=1e-5) == 80.0
    assert pytest.approx(eta_util, rel=1e-5) == 50.0
    assert pytest.approx(eta_gpu_agmd, rel=1e-5) == 40.0


